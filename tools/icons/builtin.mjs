// The icons the components draw themselves: src/material/builtin.ts, the Material Symbols that the source
// names as a string (outside stories and tests), taken from src/material/icons.ts. They ship in the main
// bundle, so they render at once and on the server; every other name loads with the full set.
//   node tools/icons/builtin.mjs           write src/material/builtin.ts (after a component starts using a new icon)
//   node tools/icons/builtin.mjs --check   exit 1 if it is out of date (the Icon names test runs this)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const P = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = path.join(P, 'src', 'material', 'builtin.ts');

export function builtin() {
  const icons = new Map([...fs.readFileSync(path.join(P, 'src', 'material', 'icons.ts'), 'utf8')
    .matchAll(/name: "([a-z0-9_]+)", d: "([^"]+)"/g)].map((m) => [m[1], m[2]]));
  const keep = new Set();
  const scan = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const f = path.join(dir, e.name);
      if (e.isDirectory()) { if (e.name !== 'material') scan(f); continue; }
      if (!/\.tsx?$/.test(e.name) || /\.(stories|test)\./.test(e.name)) continue;
      for (const m of fs.readFileSync(f, 'utf8').matchAll(/["'`]([a-z][a-z0-9_]{1,40})["'`]/g)) if (icons.has(m[1])) keep.add(m[1]);
    }
  };
  scan(path.join(P, 'src'));
  const names = [...keep].sort();
  return { names, text: '/* Generated by tools/icons/builtin.mjs from src/material/icons.ts (Material Symbols Rounded, Apache 2.0); run it, don\'t edit this. */\n'
    + 'import type { IconData } from "./types";\n\n'
    + '/** The icons the components draw themselves, in the main bundle so they render at once and on the server.\n'
    + ' * Every other name loads with the full set (src/material/icons.ts) the first time it is drawn. */\n'
    + 'export const BUILTIN_ICONS: readonly IconData[] = [\n' + names.map((n) => `  { name: "${n}", d: "${icons.get(n)}" },\n`).join('') + '];\n' };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { names, text } = builtin();
  if (process.argv.includes('--check')) {
    const ok = fs.readFileSync(OUT, 'utf8') === text;
    console.log(ok ? `Built-in icons are up to date (${names.length})` : 'src/material/builtin.ts is out of date: run node tools/icons/builtin.mjs');
    process.exit(ok ? 0 : 1);
  }
  fs.writeFileSync(OUT, text);
  console.log(`Wrote src/material/builtin.ts (${names.length} built in)`);
}
