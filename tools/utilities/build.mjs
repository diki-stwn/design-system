// The utility classes: src/styles/utilities.template.css → src/styles/utilities.css, with the @each and
// @responsive loops (template.mjs) expanded over the tokens in tokens.json. npm run build runs it first, and
// Storybook and Vitest run it as they start, so a new token gets its classes everywhere. The output isn't
// committed; edit the template.
//   node tools/utilities/build.mjs [project dir]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { families } from './families.mjs';
import { expand } from './template.mjs';

export function buildUtilities(P) {
  const tokens = JSON.parse(fs.readFileSync(path.join(P, 'tokens.json'), 'utf8'));
  const template = fs.readFileSync(path.join(P, 'src', 'styles', 'utilities.template.css'), 'utf8');
  const css = expand(template, families(tokens));
  const file = '/* Generated by tools/utilities/build.mjs from utilities.template.css and tokens.json; edit those, not this. */\n' + css;
  const out = path.join(P, 'src', 'styles', 'utilities.css');
  // Only write when it changed, so a running Storybook doesn't reload for nothing.
  if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== file) fs.writeFileSync(out, file);
  return css;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  buildUtilities(path.resolve(process.argv[2] || path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..')));
}
